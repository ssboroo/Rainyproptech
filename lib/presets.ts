export function category(p: Project): "interior" | "exterior" | "master_plan" {
  return projects[p].group === "interior"
    ? "interior"
    : projects[p].group === "site"
      ? "master_plan"
      : "exterior";
}
export function isInteriorStyle(s: Style) {
  return styles[s].group === "interior";
}
